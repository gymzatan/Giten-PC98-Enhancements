#!/usr/bin/env python3
"""Freeze the analysed script grammar into tools/ddsgrammar.py.

Inputs are the outputs of vmscan.py (slow; run it once per EXE):

    dec/vmscan_cmds.txt    handler -> operand signature, one line per handler
    dec/vmscan_values.txt  value type -> operand signature

The command codes come straight from the dispatch table in DDS98.EXE, because
the vmscan listing abbreviates long code lists.
"""
import re
import struct
import sys

from mz import MZ

VM_SEG, TABLE, COUNT, DEFAULT = 0x1603, 0x5AA6, 0x2FF, 0x6F1C
REDISPATCH = {0x01D: 0x300, 0x01E: 0x200, 0x01F: 0x100}     # prefix byte -> page base
ALIAS = {0x162: 0x1DE}                                       # 1603:60D4 mov si,1DEh; jmp head


def main(exe="files/DDS98/DDS98.EXE", out="tools/ddsgrammar.py"):
    img = bytes(MZ(exe).image)
    table = [struct.unpack_from("<H", img, VM_SEG * 16 + TABLE + 2 * i)[0] for i in range(COUNT)]

    sig_of = {}
    for line in open("dec/vmscan_cmds.txt", encoding="utf-8"):
        m = re.match(r"^\S+\s+1603:([0-9A-F]{4})\s+(\S*)→(\S+)$", line.strip())
        if not m:
            raise SystemExit(f"unparsed vmscan line: {line!r}")
        handler, sig, exit_ = int(m.group(1), 16), m.group(2), m.group(3)
        if exit_ not in ("stop@1603:6F1C", "stop@1603:6F1E", "stop@1603:5A7B"):
            raise SystemExit(f"handler {handler:04X} did not resolve: {exit_}")
        sig_of[handler] = "" if sig == "-" else sig

    commands = {}
    for code, h in enumerate(table):
        if h == DEFAULT:
            continue
        if code in REDISPATCH or code in ALIAS:
            continue
        commands[code] = sig_of[h]

    values = {}
    for line in open("dec/vmscan_values.txt", encoding="utf-8"):
        m = re.match(r"^type ([0-9A-F]{2}) @1603:[0-9A-F]{4}\s+(\S*)→ret$", line.strip())
        if not m:
            raise SystemExit(f"unparsed value line: {line!r}")
        values[int(m.group(1), 16)] = "" if m.group(2) == "-" else m.group(2)

    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write('"""DDS98 script grammar, generated by mkgrammar.py from vmscan.py output.\n\n')
        f.write("COMMANDS: command code -> operand signature. Codes not listed fall to the\n")
        f.write("dispatcher's default case (no operands, no effect).\n")
        f.write("VALUES:   value type byte -> operand signature after the type byte.\n")
        f.write('"""\n\n')
        f.write(f"PREFIX = {{{', '.join(f'0x{k:02X}: 0x{v:03X}' for k, v in REDISPATCH.items())}}}\n")
        f.write(f"ALIAS = {{{', '.join(f'0x{k:03X}: 0x{v:03X}' for k, v in ALIAS.items())}}}\n\n")
        f.write("COMMANDS = {\n")
        for code in sorted(commands):
            f.write(f"    0x{code:03X}: {commands[code]!r},\n")
        f.write("}\n\nVALUES = {\n")
        for t in sorted(values):
            f.write(f"    0x{t:02X}: {values[t]!r},\n")
        f.write("}\n")
    print(f"{out}: {len(commands)} commands, {len(values)} value types")


if __name__ == "__main__":
    main(*sys.argv[1:])
